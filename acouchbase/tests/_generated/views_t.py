    async def test_view_query_startkey_docid(self, cb_env: AsyncTestEnvironment) -> None:
        batch_id = cb_env.data_provider.vehicle_batch_id
        key = max(view_keys(batch_id))
        startkey_docid = docids_for_key(batch_id, key)[-1]
