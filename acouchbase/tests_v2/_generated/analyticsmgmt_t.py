    @pytest.mark.asyncio
    @pytest.mark.usefixtures('cb_env')
    async def test_couchbase_remote_link_encode(self) -> None:
        link = CouchbaseRemoteAnalyticsLink('test_dataverse',
                                            'cbremote',
                                            'localhost',
                                            CouchbaseAnalyticsEncryptionSettings(AnalyticsEncryptionLevel.NONE),
                                            username='Administrator',
                                            password='password')

        encoded = link.as_dict()
        cb_assert_isinstance(encoded, dict, what='encoded link')
        cb_assert_eq(encoded.get('hostname'), 'localhost', what='encoded hostname')
        cb_assert_eq(encoded.get('link_type'), AnalyticsLinkType.CouchbaseRemote.value,
                     what='encoded link type')
        link_encryption = encoded.get('encryption', None)
        # A bare isinstance rather than cb_assert_isinstance, in both halves: the helper
        # checks the same thing but is opaque to mypy, and as_dict() is Dict[str, Any], so
        # without the narrowing every .get() below reads as a call on `Any | None`.
        assert isinstance(link_encryption, dict), 'The encoded link carries no encryption block.'
        cb_assert_eq(link_encryption.get('encryption_level'), AnalyticsEncryptionLevel.NONE.value,
                     what='encoded encryption level')
        cb_assert_eq(encoded.get('username'), 'Administrator', what='encoded username')
        cb_assert_eq(encoded.get('password'), 'password', what='encoded password')

        link = CouchbaseRemoteAnalyticsLink('test_dataverse',
                                            'cbremote',
                                            'localhost',
                                            CouchbaseAnalyticsEncryptionSettings(
                                                AnalyticsEncryptionLevel.FULL,
                                                certificate=bytes('certificate', 'utf-8'),
                                                client_certificate=bytes('clientcertificate', 'utf-8'),
                                                client_key=bytes('clientkey', 'utf-8')))

        encoded = link.as_dict()
        cb_assert_isinstance(encoded, dict, what='encoded link')
        cb_assert_eq(encoded.get('hostname'), 'localhost', what='encoded hostname')
        cb_assert_eq(encoded.get('link_type'), AnalyticsLinkType.CouchbaseRemote.value,
                     what='encoded link type')
        link_encryption = encoded.get('encryption', None)
        assert isinstance(link_encryption, dict), 'The encoded link carries no encryption block.'
        cb_assert_eq(link_encryption.get('encryption_level'), AnalyticsEncryptionLevel.FULL.value,
                     what='encoded encryption level')
        cb_assert_eq(link_encryption.get('certificate'), 'certificate', what='encoded certificate')
        cb_assert_eq(link_encryption.get('client_certificate'), 'clientcertificate',
                     what='encoded client certificate')
        cb_assert_eq(link_encryption.get('client_key'), 'clientkey', what='encoded client key')

