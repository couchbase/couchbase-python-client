    @pytest.mark.asyncio
    async def test_v6_dataverse_name_parsing(self, cb_env: AsyncTestEnvironment) -> None:
        EnvironmentFeatures.check_if_feature_not_supported(ServerFeatures.AnalyticsDataversePathNames,
                                                           cb_env.server_context)
        aixm = cb_env.get_manager(AsyncTestEnvironmentAnalyticsIndexManager)

        # A dotted name is accepted from 6.0 and then rejected again by 6.6, so the branch
        # picks which of two behaviours to assert rather than whether to run.  That is why
        # it is a version compare and not a feature: nothing here is a capability a later
        # server gains.
        version = cb_env.server_version_short
        if version is not None and version >= 6.6:
            with pytest.raises(CouchbaseException):
                await aixm.create_dataverse('test.test_dataverse',
                                            CreateDataverseOptions(ignore_if_exists=True))
        else:
            await aixm.create_dataverse('test.test_dataverse',
                                        CreateDataverseOptions(ignore_if_exists=True))

        await aixm.drop_dataverse('test.test_dataverse', ignore_if_not_exists=True)

        # A `/` path name is not valid before 7.0.
        with pytest.raises((InternalServerFailureException, CouchbaseException)):
            await aixm.create_dataverse('test/test_dataverse',
                                        CreateDataverseOptions(ignore_if_exists=True))

