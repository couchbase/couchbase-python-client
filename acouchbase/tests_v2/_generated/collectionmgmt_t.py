    @pytest.mark.asyncio
    async def test_create_collection_invalid_args(self, cb_env: AsyncTestEnvironment) -> None:
        mgr = cb_env.get_manager(AsyncTestEnvironmentCollectionMgmtManager)
        spec = CollectionSpec('coll', 'scope')

        # A CollectionSpec positionally and again as the `collection` keyword.
        with pytest.raises(InvalidArgumentException):
            await mgr.create_collection(spec, collection=spec)
        # The deprecated form mixed with a current-signature keyword.
        with pytest.raises(InvalidArgumentException):
            await mgr.create_collection(spec, scope_name=self.DEFAULT_SCOPE)
        with pytest.raises(InvalidArgumentException):
            await mgr.create_collection(spec, settings=CreateCollectionSettings())
        with pytest.raises(InvalidArgumentException):
            await mgr.create_collection(collection=spec, collection_name='c')
        # The `collection` keyword alongside positional arguments.
        with pytest.raises(InvalidArgumentException):
            await mgr.create_collection(self.DEFAULT_SCOPE, collection=spec)
        # The same name given twice, positionally and by keyword.
        with pytest.raises(InvalidArgumentException):
            await mgr.create_collection(self.DEFAULT_SCOPE, scope_name=self.DEFAULT_SCOPE)
        with pytest.raises(InvalidArgumentException):
            await mgr.create_collection(self.DEFAULT_SCOPE, 'c', collection_name='c')
        with pytest.raises(InvalidArgumentException):
            await mgr.create_collection(self.DEFAULT_SCOPE, 'c', CreateCollectionSettings(),
                                        settings=CreateCollectionSettings())
        # settings= holding something that is not a settings object.
        with pytest.raises(InvalidArgumentException):
            await mgr.create_collection(self.DEFAULT_SCOPE, 'c', settings='not-a-settings')

