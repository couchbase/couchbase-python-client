        # The base exception, not ParsingFailedException, and that is a statement about the
        # SDK rather than about analytics.  The core reports an analytics syntax error as
        # compilation_failure, which the exception map does not carry (PYCBC-1920), so the same
        # mistake that raises ParsingFailedException from query arrives here unmapped.
        # Asserting the base class keeps this test honest about today and still passes once it
        # is mapped.
        with pytest.raises(CouchbaseException):
            result = cb_env.cluster.analytics_query(INVALID_STATEMENT)
            await cb_env.drain_rows(result)
        http_validator.validate_http_op(OpName.AnalyticsQuery, validate_error=True)

