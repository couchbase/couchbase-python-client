# typecheck.sh
#
# Generates the protobuf code into a temporary directory and type checks the performer against it,
# with the settings in pyproject.toml.  Run from anywhere; extra arguments go to mypy.
#
# The performer's own generated/ is left alone: this runs under pre-commit's environment, whose
# protobuf can be newer than the one the performer runs with, and code generated by a newer protobuf
# refuses to import under an older runtime.

set -e

out=$(mktemp -d)
trap 'rm -rf "$out"' EXIT

cd "$(dirname "$0")/.."
./bin/generate.sh "$out"
cd ../..

# The generated code imports itself by bare top-level names, so it is searched as a root of its own.
# A generated/ left by the performer's own generate.sh is excluded, or each module would be found
# twice.
MYPYPATH="$out" python -m mypy --config-file pyproject.toml \
    --exclude '^tools/fit_performer/generated/' "$@" tools/fit_performer
