import pathlib
import subprocess

import pytest

from tools.check_license_headers import (HASH,
                                         C,
                                         Style,
                                         audit,
                                         source_files,
                                         style_for,
                                         with_header,
                                         year_of)

BANNER = '# !! AUTO-GENERATED by tools/autogen: DO NOT EDIT MANUALLY !!\n'


@pytest.mark.parametrize('path, expected', [
    ('couchbase/cluster.py', HASH),
    ('couchbase/protocol/classic/_core.pyi', HASH),
    ('tools/fit_performer/bin/generate.sh', HASH),
    ('src/connection.cxx', C),
    ('src/connection.hxx', C),
    ('CMakeLists.txt', HASH),
    ('tools/fit_performer/Dockerfile', HASH),
    ('examples/dockerfiles/rhel8/binary_install.Dockerfile', HASH),
    ('requirements.txt', None),
    ('docs/index.rst', None),
    ('tools/fit_performer/proto/performer.proto', None),
    ('tools/autogen/templates/bindings/pycbc_kv_request.cxx.jinja2', None),
])
def test_style_for(path: str, expected: Style | None) -> None:
    assert style_for(path) is expected


@pytest.mark.parametrize('style', [HASH, C])
def test_written_header_reads_back(style: Style) -> None:
    text = with_header('x = 1\n', style, 2026)
    assert year_of(text, style) == 2026
    assert text.endswith('\n\nx = 1\n')


def test_any_year_since_the_first_passes() -> None:
    assert year_of(with_header('x = 1\n', HASH, 2019), HASH) == 2019


@pytest.mark.parametrize('text', [
    '',
    'x = 1\n',
    '# a comment, not a license\nx = 1\n',
])
def test_missing_header(text: str) -> None:
    assert year_of(text, HASH) is None


def test_spacing_is_part_of_the_header() -> None:
    good = with_header('x = 1\n', HASH, 2026)
    assert year_of('\n' + good, HASH) is None
    assert year_of(good.replace('\n\nx', '\n\n\nx'), HASH) is None
    assert year_of(good.replace('\n\nx', '\nx'), HASH) is None


def test_header_only_file_ends_with_the_header() -> None:
    assert with_header('', HASH, 2026) == HASH.header(2026)


def test_rewrite_keeps_everything_below_the_header() -> None:
    old = '# Copyright 2021, Couchbase, Inc.\n# limitations under the License.\n\n\nimport os\n'
    assert with_header(old, HASH, 2026) == HASH.header(2026) + '\nimport os\n'


def test_comment_after_the_header_is_not_part_of_it() -> None:
    text = HASH.header(2022) + BANNER + 'x = 1\n'
    assert with_header(text, HASH, 2026) == HASH.header(2026) + '\n' + BANNER + 'x = 1\n'


def test_header_goes_in_front_of_another_comment() -> None:
    text = '# just a comment\nx = 1\n'
    assert with_header(text, HASH, 2026) == HASH.header(2026) + '\n' + text


def test_shebang_stays_first() -> None:
    text = with_header('#!/bin/bash\nset -e\n', HASH, 2026)
    assert text == '#!/bin/bash\n\n' + HASH.header(2026) + '\nset -e\n'
    assert year_of(text, HASH) == 2026


def _tree(tmp_path: pathlib.Path, files: dict[str, str]) -> list[str]:
    for name, text in files.items():
        (tmp_path / name).write_text(text)
    return sorted(files)


def test_old_year_passes_unless_staged(tmp_path: pathlib.Path) -> None:
    paths = _tree(tmp_path, {'a.py': with_header('x = 1\n', HASH, 2022),
                             'b.py': with_header('x = 1\n', HASH, 2022)})
    problems = audit(tmp_path, paths, {'b.py'}, 2026, fix=False, bump_all=False)
    assert [p.split(':')[0] for p in problems] == ['b.py']


def test_generated_file_keeps_its_generators_year(tmp_path: pathlib.Path) -> None:
    paths = _tree(tmp_path, {'g.py': HASH.header(2022) + '\n' + BANNER})
    assert audit(tmp_path, paths, {'g.py'}, 2026, fix=False, bump_all=True) == []


def test_fix_rewrites_and_still_reports(tmp_path: pathlib.Path) -> None:
    paths = _tree(tmp_path, {'a.py': 'x = 1\n', 'b.py': with_header('x = 1\n', HASH, 2022)})
    problems = audit(tmp_path, paths, set(), 2026, fix=True, bump_all=True)
    assert len(problems) == 2
    for name in paths:
        assert year_of((tmp_path / name).read_text(), HASH) == 2026
    assert audit(tmp_path, paths, set(), 2026, fix=False, bump_all=True) == []


def test_future_year_fails(tmp_path: pathlib.Path) -> None:
    paths = _tree(tmp_path, {'a.py': with_header('x = 1\n', HASH, 2030)})
    assert audit(tmp_path, paths, set(), 2026, fix=False, bump_all=False)


def test_another_holders_notice_is_left_alone(tmp_path: pathlib.Path) -> None:
    text = '# Copyright 2020 Someone Else\n# limitations under the License.\n\nx = 1\n'
    paths = _tree(tmp_path, {'a.py': text})
    problems = audit(tmp_path, paths, set(), 2026, fix=True, bump_all=False)
    assert problems and 'by hand' in problems[0]
    assert (tmp_path / 'a.py').read_text() == text


def test_untracked_files_are_not_part_of_the_tree(tmp_path: pathlib.Path) -> None:
    subprocess.run(['git', 'init', '-q', str(tmp_path)], check=True)
    _tree(tmp_path, {'tracked.py': 'x = 1\n', 'untracked.py': 'x = 1\n'})
    subprocess.run(['git', 'add', 'tracked.py'], cwd=tmp_path, check=True)
    assert source_files(tmp_path) == ['tracked.py']
