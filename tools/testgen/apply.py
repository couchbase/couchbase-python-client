"""Apply an edit list to the original source text.

Edits are (line, col) -> (end_line, end_col) replacements.  Applying them in reverse
document order means earlier positions are still valid when a later edit has already
been written, so no offset bookkeeping is needed.

Edits at the same position are ordered deliberately, because each one written there lands
to the left of those written before it.  So whatever must end up innermost is written first.
"""
from __future__ import annotations

from tools.testgen.transform import Edit


def apply_edits(src: str, edits: list[Edit]) -> str:
    lines = src.splitlines(keepends=True)

    def sort_key(e: Edit) -> tuple[int, int, int]:
        # A replacement goes first, since an insertion written ahead of it would shift the
        # span it replaces: `(await build_environment(...)).cluster` otherwise renders as
        # `build_async_environmentronment(...)).cluster`.  The `(await ` wrapping a call goes
        # next, inside any `await ` of the call it is the base of, which is how
        # `a().b()` becomes `await (await a()).b()`.  The rest keep emission order, which
        # is what puts `async ` inside the asyncio marker at a `def` with no decorators.
        if (e.line, e.col) != (e.end_line, e.end_col):
            rank = 0
        elif e.text.startswith('(await'):
            rank = 1
        else:
            rank = 2
        return (-e.line, -e.col, rank)

    for e in sorted(edits, key=sort_key):
        if e.line == e.end_line:
            line = lines[e.line]
            lines[e.line] = line[:e.col] + e.text + line[e.end_col:]
        else:
            first = lines[e.line][:e.col]
            # end_line == len(lines) means "through the last line inclusive".  Both deletion
            # helpers in the transformer walk `end` forward over trailing blank lines and stop
            # at len(self.lines), so a class or method that is the last thing in the file
            # produces exactly that span, and indexing it unguarded is an IndexError.
            last = lines[e.end_line][e.end_col:] if e.end_line < len(lines) else ''
            lines[e.line] = first + e.text + last
            for i in range(e.line + 1, min(e.end_line + 1, len(lines))):
                lines[i] = ''
    return ''.join(lines)


HEADER = """# !! AUTO-GENERATED by tools/testgen: DO NOT EDIT MANUALLY !!
# Source: {source}
# Regenerate with: python -m tools.testgen generate --write
"""


def add_header(text: str, source: str) -> str:
    """Insert the generated-file banner after the Apache licence block.

    Above the licence would put a non-licence comment in front of the copyright notice;
    below the imports would put it out of sight.  The first blank line after the last
    leading comment is the seam.
    """
    lines = text.splitlines(keepends=True)
    i = 0
    while i < len(lines) and (lines[i].startswith('#') or lines[i].strip() == ''):
        i += 1
        if i < len(lines) and not lines[i].startswith('#') and lines[i].strip() != '':
            break
    banner = HEADER.format(source=source)
    return ''.join(lines[:i]) + banner + '\n' + ''.join(lines[i:])
