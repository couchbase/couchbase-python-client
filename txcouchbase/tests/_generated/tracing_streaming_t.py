    # operation carries: a cluster-level query none of it, the same query on a scope the bucket
    # and the scope, a view query the bucket alone because a design document belongs to one.
    # Each test states which it expects and the validator asserts the others are absent, since
    # a scope name attached to a cluster-level query is a defect nothing else would notice.
    #
    # The statement is recorded only when the query carries parameters, which is why three
    # quarters of these tests expect no statement attribute: a parameterised statement holds
    # placeholders where a literal one can hold anything the caller inlined, so only the
    # parameterised form is safe to put in a span.
    #
    # The rows have to be drained before the span ends: a streaming operation returns before the
    # server has finished answering and the span is ended when the stream ends.  Draining goes
    # through the environment helpers rather than a comprehension over `rows()`, which is what
