def search_index_name() -> str:
    """A name no other test has used, so no drop elsewhere can reach this test's index.

    A fixed name is shared by every parametrization, and those can run on different workers
    at once.  On one worker, the parametrization after the first recreates the name the one
    before it just dropped, and the recreated index can stay unreadable for well past the 30s
    the test waits.  The cause is not established.
    """
    return f'{SEARCH_INDEX_NAME}-{uuid4().hex[:8]}'


